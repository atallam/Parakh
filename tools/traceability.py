"""Traceability: acceptance criteria → tests (plan 14 §5; AC-F21.15).

- Reads every `AC-Fnn.m` from docs/plan/08_FEATURE_SPEC.md.
- Finds tests marked `@pytest.mark.ac("AC-F21.1", ...)` by parsing tests/ (no import needed).
- Optionally reads a JUnit XML from pytest (`--junit`) for each test's last result.
- Writes docs/TRACEABILITY.md. With `--check` it fails when an AC listed in
  tools/traceability_due.txt has no test, or a test cites an AC that doesn't exist.

The due list grows phase by phase: an AC joins it in the phase its feature is due (plan 09).
UAT steps (docs/uat/) that prove an AC are added to the table from UAT-0 on.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "docs" / "plan" / "08_FEATURE_SPEC.md"
TESTS = ROOT / "tests"
DUE = ROOT / "tools" / "traceability_due.txt"
OUT = ROOT / "docs" / "TRACEABILITY.md"
AC_LINE = re.compile(r"^- (AC-F(\d+)\.\d+)\b[^:]*:\s*(.+)$")


def spec_acs(spec: Path = SPEC) -> dict[str, tuple[str, str]]:
    """AC id → (feature, text)."""
    out = {}
    for line in spec.read_text(encoding="utf-8").splitlines():
        m = AC_LINE.match(line.strip())
        if m:
            out[m.group(1)] = (f"F{m.group(2)}", m.group(3).strip())
    return out


def _ac_args(decorator: ast.expr) -> list[str]:
    """AC ids from `pytest.mark.ac("AC-…", …)` decorators."""
    if not isinstance(decorator, ast.Call):
        return []
    f = decorator.func
    if isinstance(f, ast.Attribute) and f.attr == "ac":
        return [
            a.value
            for a in decorator.args
            if isinstance(a, ast.Constant) and isinstance(a.value, str)
        ]
    return []


def test_acs(tests: Path = TESTS) -> dict[str, list[str]]:
    """AC id → test ids ("tests/unit/test_x.py::test_y")."""
    out: dict[str, list[str]] = defaultdict(list)
    for path in sorted(tests.rglob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        rel = path.relative_to(ROOT).as_posix()
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and node.name.startswith(
                "test"
            ):
                for dec in node.decorator_list:
                    for ac in _ac_args(dec):
                        out[ac].append(f"{rel}::{node.name}")
    return dict(out)


def junit_results(path: Path | None) -> dict[str, str]:
    if not path or not path.exists():
        return {}
    results = {}
    for case in ET.parse(path).getroot().iter("testcase"):
        name = case.get("name", "").split("[")[0]
        file = (case.get("classname") or "").replace(".", "/")
        status = (
            "fail" if case.find("failure") is not None or case.find("error") is not None else "pass"
        )
        if case.find("skipped") is not None:
            status = "skip"
        key = f"{file}.py::{name}"
        results[key] = "fail" if results.get(key) == "fail" else status
    return results


def due() -> list[str]:
    if not DUE.exists():
        return []
    return [
        line.split("#")[0].strip()
        for line in DUE.read_text(encoding="utf-8").splitlines()
        if line.split("#")[0].strip()
    ]


def build(junit: Path | None = None) -> tuple[str, list[str]]:
    acs = spec_acs()
    tests = test_acs()
    results = junit_results(junit)
    problems = [f"{t}: cites unknown {ac}" for ac, ts in tests.items() if ac not in acs for t in ts]
    problems += [f"{ac} is due but has no test" for ac in due() if ac not in tests]
    problems += [f"{ac} in the due list isn't in plan 08" for ac in due() if ac not in acs]
    due_set = set(due())
    lines = [
        "<!-- Generated by `python tools/traceability.py`. Do not edit by hand. -->\n",
        "# Traceability: acceptance criteria → tests\n",
        f"{len(tests)} of {len(acs)} acceptance criteria have tests; {len(due_set)} are due now "
        "(tools/traceability_due.txt).\n",
        "| AC | Feature | Due | Tests | Last result |",
        "|---|---|---|---|---|",
    ]
    for ac, (feature, _text) in sorted(
        acs.items(), key=lambda kv: (int(kv[1][0][1:]), float(kv[0].split(".")[1]))
    ):
        ts = tests.get(ac, [])
        res = sorted({results.get(t, "—") for t in ts}) if ts else []
        lines.append(
            f"| {ac} | {feature} | {'✅' if ac in due_set else ''} | "
            f"{'<br>'.join(f'`{t}`' for t in ts) or '—'} | {', '.join(res) or '—'} |"
        )
    return "\n".join(lines) + "\n", problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Acceptance criteria → tests (plan 14 §5)")
    parser.add_argument("--junit", type=Path)
    parser.add_argument(
        "--check", action="store_true", help="fail on missing due ACs or unknown AC ids"
    )
    args = parser.parse_args(argv)
    content, problems = build(args.junit)
    OUT.write_text(content, encoding="utf-8", newline="\n")
    for p in problems:
        print(p, file=sys.stderr)
    print(f"wrote {OUT.relative_to(ROOT)} · {len(problems)} problem(s)")
    return 1 if (args.check and problems) else 0


if __name__ == "__main__":
    raise SystemExit(main())
