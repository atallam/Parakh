"""Generate supabase/seed.sql from config/universe.yaml, so the two can't drift.

`uv run python tools/make_seed.py` writes it; `--check` fails if it is stale (CI and a test).
The local Supabase stack loads seed.sql on `supabase start` / `supabase db reset`.
"""

from __future__ import annotations

import sys
from pathlib import Path

from parakh.configs import load_file
from parakh.configs.models import UniverseConfig

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "supabase" / "seed.sql"


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render() -> str:
    universe = load_file("universe.yaml", UniverseConfig)
    rows = [
        f"  ({_q(s.isin)}, {_q(s.symbol)}, {_q(s.name)}, {('date ' + _q(s.listed_on.isoformat())) if s.listed_on else 'null'})"
        for s in universe.pilot
    ]
    return (
        "-- Generated by tools/make_seed.py from config/universe.yaml. Do not edit by hand.\n"
        "-- The pilot universe (plan 13 D3), keyed by ISIN.\n"
        "insert into public.securities (isin, symbol, name, listing_date) values\n"
        + ",\n".join(rows)
        + "\non conflict (isin) do update set symbol = excluded.symbol, name = excluded.name,\n"
        "  listing_date = coalesce(excluded.listing_date, public.securities.listing_date);\n"
    )


def main(argv: list[str]) -> int:
    content = render()
    current = SEED.read_text(encoding="utf-8") if SEED.exists() else None
    if "--check" in argv:
        if current != content:
            print(
                "supabase/seed.sql is stale: run `uv run python tools/make_seed.py`",
                file=sys.stderr,
            )
            return 1
        print("seed.sql up to date")
        return 0
    SEED.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {SEED.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
