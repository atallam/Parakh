"""Generate supabase/seed.sql from config (universe.yaml, sources.yaml), so they can't drift.

`uv run python tools/make_seed.py` writes it; `--check` fails if it is stale (CI and a test).
The local Supabase stack loads seed.sql on `supabase start` / `supabase db reset`.
"""

from __future__ import annotations

import sys
from pathlib import Path

from parakh.configs import load_file
from parakh.configs.models import SourcesConfig, UniverseConfig

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "supabase" / "seed.sql"


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _array(items: list[str]) -> str:
    return "array[" + ", ".join(_q(i) for i in items) + "]::text[]"


def render() -> str:
    universe = load_file("universe.yaml", UniverseConfig)
    registry = load_file("sources.yaml", SourcesConfig)
    securities = [
        f"  ({_q(s.isin)}, {_q(s.symbol)}, {_q(s.name)}, {('date ' + _q(s.listed_on.isoformat())) if s.listed_on else 'null'})"
        for s in universe.pilot
    ]
    sources = [
        f"  ({_q(x.id)}, {_q(x.tier)}, {_array(x.data_types)}, {_q(x.access)}, {_q(x.terms)}, {_q(x.cadence)})"
        for x in registry.sources
    ]
    history = [
        f"  ({_q(p.isin)}, {_q(s.isin)}, date {_q(p.changed_on.isoformat())}, {_q(p.reason)}, {_q(p.source)})"
        for s in universe.pilot
        for p in s.previous_isins
    ]
    out = (
        "-- Generated by tools/make_seed.py from config/universe.yaml and config/sources.yaml.\n"
        "-- Do not edit by hand.\n\n"
        "-- The pilot universe (plan 13 D3), keyed by ISIN.\n"
        "insert into public.securities (isin, symbol, name, listing_date) values\n"
        + ",\n".join(securities)
        + "\non conflict (isin) do update set symbol = excluded.symbol, name = excluded.name,\n"
        "  listing_date = coalesce(excluded.listing_date, public.securities.listing_date);\n\n"
        "-- Source registry (plan 10 §13).\n"
        "insert into public.sources (source_id, tier, data_types, access_method, terms_note,\n"
        "  refresh_cadence) values\n"
        + ",\n".join(sources)
        + "\non conflict (source_id) do update set tier = excluded.tier,\n"
        "  data_types = excluded.data_types, access_method = excluded.access_method,\n"
        "  terms_note = excluded.terms_note, refresh_cadence = excluded.refresh_cadence;\n"
    )
    if history:
        out += (
            "\n-- ISIN changes from splits and face-value changes (spike ④).\n"
            "insert into public.isin_history (old_isin, new_isin, changed_on, reason, source_id) values\n"
            + ",\n".join(history)
            + "\non conflict (old_isin, new_isin) do nothing;\n"
        )
    return out


def main(argv: list[str]) -> int:
    content = render()
    current = SEED.read_text(encoding="utf-8") if SEED.exists() else None
    if "--check" in argv:
        if current != content:
            print(
                "supabase/seed.sql is stale: run `uv run python tools/make_seed.py`",
                file=sys.stderr,
            )
            return 1
        print("seed.sql up to date")
        return 0
    SEED.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {SEED.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
