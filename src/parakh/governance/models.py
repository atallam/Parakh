def _agent_facts(aid: str) -> dict[str, object]:
    b = load_all()
    spec = b.agents.agents[AGENT_CARDS[aid]["key"]]
    d = b.agents.defaults
    return {
        "model": spec.model_id or d.model_id,
        "prompt": spec.prompt_id,
        "turns": spec.max_turns or d.max_turns,
        "budget": spec.token_budget or d.token_budget,
        "tools": list(spec.allowed_tools),
    }


def agent_card_md(aid: str) -> str:
    c, f = AGENT_CARDS[aid], _agent_facts(aid)

    def bullets(xs: list[str]) -> str:
        return "\n".join(f"- {x}" for x in xs)

    tools = [f"`{str(t).removeprefix('mcp__parakh__')}`" for t in f["tools"]]  # type: ignore[attr-defined]
    return (
        HEADER
        + f"# Agent card: {c['title']}\n\n"
        + f"`{c['key']}` · prompt `{f['prompt']}` · model `{f['model']}` · owner {OWNER} · "
        + f"max {f['turns']} turns · {f['budget']} tokens\n\n"
        + f"## Job\n\n{c['job']}\n\n"
        + f"## Inputs\n\n{bullets(c['inputs'])}\n\n"
        + f"## Allowed tools\n\n{bullets(tools)}\n\n"
        + f"## Outputs\n\n{bullets(c['outputs'])}\n\n"
        + f"## Guardrails\n\n{bullets(c['guardrails'])}\n\n"
        + f"## Limitations\n\n{bullets(c['limitations'])}\n\n"
        + "## Audit\n\nEvery run writes `AUD.AGENT.START` and `AUD.AGENT.END`; every tool call writes `AUD.MCP.TOOL_CALL` (see [AUDIT_EVENTS.md](../AUDIT_EVENTS.md), [TOOLS.md](../TOOLS.md)).\n\n"
        + "## Validation\n\nPending: shadow-mode review (UAT-2) and the L7 trajectory evals in `tests/agents/`.\n"
    )


def _hash(name: str) -> str:
    return hashlib.sha256((config_dir() / name).read_bytes().replace(b"\r\n", b"\n")).hexdigest()[
        :8
    ]


def _versions() -> dict[str, str]:
    b = load_all()
    reg = discover()
    return {
        "value": reg.lenses["value"].lens_version,
        "momentum": reg.lenses["momentum"].lens_version,
        "verdict_policy": b.verdict_policy.policy_version,
    }


def inventory_md() -> str:
    v = _versions()
    rows = [
        HEADER + "# Model inventory\n",
        "Every lens and the verdict policy. Status is `active`, `informational` or `retired`. "
        "Validation and calibration say 'pending' until they have actually happened.\n",
        "| ID | Version | Status | Owner | Config hash | Last validation | Last calibration | Card |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for mid, card in CARDS.items():
        rows.append(
            f"| `{mid}` | {v[mid]} | active | {OWNER} | `{_hash(card['config'])}` | pending (UAT-1) | pending (Phase 5) | [card](lenses/{mid}.md) |"
        )
    rows += [
        "",
        "## Agents",
        "",
        "| ID | Prompt | Model | Status | Owner | Last validation | Card |",
        "|---|---|---|---|---|---|---|",
    ]
    for aid, card in AGENT_CARDS.items():
        f = _agent_facts(aid)
        rows.append(
            f"| `{card['key']}` | `{f['prompt']}` | `{f['model']}` | shadow | {OWNER} | pending (UAT-2) | [card](agents/{aid}.md) |"
        )
    rows += [
        "",
        "The qualitative analyst, devil's advocate and watchlist curator join this table when they ship in Phase 4; prompts are versioned separately (`prompts/`).",
    ]
    return "\n".join(rows) + "\n"


def card_md(mid: str) -> str:
    c, v = CARDS[mid], _versions()[mid]
    reg = discover()
    metrics = sorted(m.id for m in reg.metrics.values() if f"LENS.{mid}" in m.used_by)
    signals = sorted(s.id for s in reg.signals.values() if s.lens == mid)

    def bullets(xs: list[str]) -> str:
        return "\n".join(f"- {x}" for x in xs)

    inputs = [f"Config: `config/{c['config']}` (hash `{_hash(c['config'])}`)."]
    if metrics:
        inputs.append(
            f"{len(metrics)} registered metrics (see [METRICS.md](../METRICS.md)), e.g. "
            + ", ".join(f"`{m}`" for m in metrics[:4])
            + "."
        )
    if signals:
        inputs.append(f"{len(signals)} registered signals (see [SIGNALS.md](../SIGNALS.md)).")
    return (
        HEADER
        + f"# Model card: {c['title']}\n\n"
        + f"`{mid}` · version {v} · owner {OWNER} · status active\n\n"
        + f"## Intended use\n\n{bullets(c['intended'])}\n\n"
        + f"## Not intended for\n\n{bullets(c['not_intended'])}\n\n"
        + f"## Inputs\n\n{bullets(inputs)}\n\n"
        + f"## Assumptions\n\n{bullets(c['assumptions'])}\n\n"
        + f"## Limitations\n\n{bullets(c['limitations'])}\n\n"
        + "## Validation\n\nPending: UAT-1 (plan 14) checks the pilot reports; Phase 5 calibrates thresholds against outcomes.\n"
    )


def model_docs() -> dict[str, str]:
    docs = {"MODELS.md": inventory_md()}
    for mid in CARDS:
        docs[f"lenses/{mid}.md"] = card_md(mid)
    for aid in AGENT_CARDS:
        docs[f"agents/{aid}.md"] = agent_card_md(aid)
    return docs


def write_model_docs(check: bool = False) -> list[str]:
    from parakh.config import REPO_ROOT

    stale = []
    for name, content in model_docs().items():
        path = REPO_ROOT / "docs" / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    return stale
