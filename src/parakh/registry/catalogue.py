"""Generate docs/METRICS.md, SIGNALS.md, RULES.md, TOOLS.md, AUDIT_EVENTS.md and SOURCES.md.

`parakh catalogue` writes them; `parakh catalogue --check` fails if any is stale, which CI runs,
so documentation can't drift from the registries (plan 04 §3.2; AC-F18.4, AC-F24.1).
"""

from __future__ import annotations

from pathlib import Path

from parakh.audit.events import AUD
from parakh.config import REPO_ROOT
from parakh.mcp.registry import TIER_MEANING, TOOLS
from parakh.registry import discover

HEADER = "<!-- Generated by `parakh catalogue`. Do not edit by hand. -->\n\n"


def _first_line(doc: str) -> str:
    return doc.strip().splitlines()[0] if doc.strip() else ""


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def metrics_md() -> str:
    reg = discover()
    lines = [
        HEADER + "# Metrics\n",
        "| ID | Unit | Inputs | Used by | Summary |",
        "|---|---|---|---|---|",
    ]
    for m in sorted(reg.metrics.values(), key=lambda s: s.id):
        lines.append(
            f"| `{m.id}` | {m.unit} | {', '.join(m.inputs)} | {', '.join(m.used_by)} | {_cell(_first_line(m.doc))} |"
        )
    if not reg.metrics:
        lines.append(
            "| — | | | | No metrics registered yet (value and momentum metrics land in Phase 2). |"
        )
    return "\n".join(lines) + "\n"


def signals_md() -> str:
    reg = discover()
    lines = [
        HEADER + "# Signals\n",
        "| ID | Name | Lens | Severity | Summary |",
        "|---|---|---|---|---|",
    ]
    for s in sorted(reg.signals.values(), key=lambda s: s.id):
        lines.append(
            f"| `{s.id}` | {_cell(s.name)} | {s.lens} | {s.severity} | {_cell(_first_line(s.doc))} |"
        )
    if not reg.signals:
        lines.append(
            "| — | | | | No signals registered yet (M01–M30 land in Phase 2, events in Phase 3). |"
        )
    return "\n".join(lines) + "\n"


def rules_md() -> str:
    reg = discover()
    lines = [HEADER + "# Rules\n", "| ID | Kind | Summary |", "|---|---|---|"]
    for r in sorted(reg.rules.values(), key=lambda s: s.id):
        lines.append(f"| `{r.id}` | {r.kind} | {_cell(_first_line(r.doc))} |")
    if not reg.rules:
        lines.append(
            "| — | | No rules registered yet (vetoes and the verdict policy land in Phase 2). |"
        )
    lenses = sorted(reg.lenses)
    lines += [
        "",
        "## Lenses",
        "",
        ", ".join(f"`LENS.{x}`" for x in lenses) if lenses else "None registered yet.",
    ]
    return "\n".join(lines) + "\n"


def tools_md() -> str:
    discover()
    lines = [
        HEADER + "# parakh-mcp tools\n",
        "Tiers: " + " · ".join(f"**{k}** {v}" for k, v in TIER_MEANING.items()) + ".\n",
        "| ID | MCP name | Tier | Toolset version | Input fields | Output | Summary |",
        "|---|---|---|---|---|---|---|",
    ]
    for t in sorted(TOOLS.values(), key=lambda s: s.id):
        fields = ", ".join(t.input_model.model_fields) or "—"
        lines.append(
            f"| `{t.id}` | `{t.agent_tool_name}` | {t.tier} | {t.toolset_version} | {fields} | "
            f"{t.output_model.__name__} | {_cell(_first_line(t.description))} |"
        )
    return "\n".join(lines) + "\n"


def sources_md() -> str:
    from parakh.configs import load_file
    from parakh.configs.models import SourcesConfig

    registry = load_file("sources.yaml", SourcesConfig)
    lines = [
        HEADER + "# Data sources\n",
        "From `config/sources.yaml` (plan 10 §13). T1 = exchange, regulator or the company's own "
        "filing; T2 = reputable aggregator; T3 = convenience or LLM-derived. When sources "
        "disagree, the higher tier wins.\n",
        "| ID | Tier | Data | Access | Terms | Cadence |",
        "|---|---|---|---|---|---|",
    ]
    for x in sorted(registry.sources, key=lambda s: (s.tier, s.id)):
        lines.append(
            f"| `{x.id}` | {x.tier} | {', '.join(x.data_types)} | {_cell(x.access)} | "
            f"{_cell(x.terms)} | {_cell(x.cadence)} |"
        )
    return "\n".join(lines) + "\n"


def audit_events_md() -> str:
    lines = [HEADER + "# Audit event types\n", "| ID | Domain |", "|---|---|"]
    lines += [f"| `{e.value}` | {e.domain} |" for e in AUD]
    return "\n".join(lines) + "\n"


CATALOGUES = {
    "METRICS.md": metrics_md,
    "SIGNALS.md": signals_md,
    "RULES.md": rules_md,
    "TOOLS.md": tools_md,
    "AUDIT_EVENTS.md": audit_events_md,
    "SOURCES.md": sources_md,
}


def generate(check: bool = False, docs_dir: Path | None = None) -> list[str]:
    """Write every catalogue, or with check=True return the names that are stale."""
    root = docs_dir or REPO_ROOT / "docs"
    from parakh.governance.models import model_docs

    stale = []
    items = [(name, build()) for name, build in CATALOGUES.items()] + list(model_docs().items())
    for name, content in items:
        path = root / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    return stale
